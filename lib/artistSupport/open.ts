/**
 * 아티스트 구독 결제가 열려 있는가.
 *
 * 코드는 토스 빌링 심사보다 먼저 배포된다. 심사가 끝나기 전에는 후원자가 결제에 닿으면
 * 안 되므로(스펙 §5·§16), 신청 API와 아티스트 페이지의 등급 카드가 이 값 하나를 본다.
 * 심사가 끝나면 Vercel 환경 변수 `NEXT_PUBLIC_ARTIST_SUPPORT_OPEN=1`을 넣고 재배포하면 된다 —
 * 코드 변경 없이 그날 바로 열린다.
 *
 * NEXT_PUBLIC_인 이유: 아티스트 페이지는 정적 생성이라 빌드 시점에 값이 박혀야 하고, 서버
 * API도 같은 변수를 본다. 비밀이 아니라 공개돼도 문제없다(열렸는지는 페이지를 보면 안다).
 *
 * **닫혀 있어도 이미 만들어진 구독의 청구·해지·카드 교체는 그대로 돈다.** 이 게이트는
 * "새로 신청받는가"만 막는다 — 심사 전에 만들어진 구독은 없어야 하지만, 있다면 그건
 * 관리자 화면에서 정리할 일이지 크론이 멈출 일이 아니다.
 */
export const isArtistSupportOpen = (): boolean => process.env.NEXT_PUBLIC_ARTIST_SUPPORT_OPEN === '1';
