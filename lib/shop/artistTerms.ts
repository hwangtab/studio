// ─── 관리자 표시 ────────────────────────────────────────────────────────────────

export type ShopArtistTermsState = 'agreed' | 'outdated' | 'none';

export interface ShopArtistTermsStatus {
  state: ShopArtistTermsState;
  /** 가장 최근에 동의한 판본과 시각(초). 동의 기록이 없으면 null. `agreed`면 현재 판본이다. */
  version: string | null;
  agreedAt: number | null;
}

const formatKst = (epochSec: number): string => {
  const d = new Date((epochSec + 9 * 3600) * 1000);
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())} ${pad(d.getUTCHours())}:${pad(d.getUTCMinutes())}`;
};

/** 관리자 화면 한 줄 — "동의(판본·일시) / 옛 판본 동의(판본·일시) / 미동의". 스튜디오 상품 계정은 위탁 계약이 없다. */
export const describeShopArtistTerms = (status: ShopArtistTermsStatus | null, isStudio: boolean): string => {
  if (isStudio) return '해당 없음(스튜디오 상품)';
  if (!status) return '확인하지 못함';
  if (status.state === 'none' || !status.version || status.agreedAt === null) return '미동의';
  const detail = `${status.version} · ${formatKst(status.agreedAt)} KST`;
  return status.state === 'agreed' ? `동의 (${detail})` : `옛 판본 동의 (${detail}) — 현재 판본 미동의`;
};
