// ---- Helpers ----

function parseFrontmatter(content) {
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) return { frontmatter: '', body: content, fmEnd: 0 };
  const fmEnd = match[0].length;
  return {
    frontmatter: match[0],
    body: content.slice(fmEnd),
    fmEnd,
  };
}

function countWords(text) {
  // Strip markdown images, links syntax, horizontal rules, headings markers, table separators
  const cleaned = text
    .replace(/!\[.*?\]\(.*?\)/g, '')        // images
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1') // links -> keep text
    .replace(/^---$/gm, '')                  // hr
    .replace(/^#{1,6}\s/gm, '')              // heading markers
    .replace(/\|[-\s|]+\|/g, '')             // table separators
    .replace(/```[\s\S]*?```/g, '')          // code blocks
    .replace(/[|*_`#>\-\[\]()]/g, ' ')       // misc markdown chars
    .replace(/\s+/g, ' ')
    .trim();
  if (!cleaned) return 0;
  return cleaned.split(/\s+/).filter(t => t.length > 0).length;
}

function findFooterCrosslinks(body) {
  // The footer is typically the last non-empty line that contains markdown links separated by |
  const lines = body.split('\n');
  for (let i = lines.length - 1; i >= 0; i--) {
    const line = lines[i].trim();
    if (!line) continue;
    // Check if it's a cross-link line (contains [text](/stories/...) patterns)
    if (/\[.*?\]\(\/stories\//.test(line) && line.includes('|')) {
      return i; // index in lines array
    }
    // If we hit actual content that's not empty/hr, stop looking
    if (line && line !== '---') break;
  }
  return -1;
}

// ---- Main ----

let modifiedCount = 0;
let alreadyOkCount = 0;
let missingContentCount = 0;
const results = [];

for (const slug of FILE_SLUGS) {
  const filePath = path.join(STORIES_DIR, `${slug}.md`);
  if (!fs.existsSync(filePath)) {
    console.error(`MISSING: ${slug}.md`);
    continue;
  }

  const raw = fs.readFileSync(filePath, 'utf-8');
  const { frontmatter, body } = parseFrontmatter(raw);
  const wordCount = countWords(body);

  if (wordCount >= MIN_WORDS) {
    alreadyOkCount++;
    results.push({ slug, before: wordCount, after: wordCount, status: 'OK' });
    continue;
  }

  // Need to add content
  const additions = TOPIC_CONTENT[slug];
  if (!additions || additions.length === 0) {
    missingContentCount++;
    results.push({ slug, before: wordCount, after: wordCount, status: 'NO_CONTENT_MAP' });
    console.error(`NO CONTENT DEFINED for ${slug} (${wordCount} words)`);
    continue;
  }

  const additionBlock = '\n\n' + additions.join(' ') + '\n';

  // Insert before footer cross-links
  const lines = body.split('\n');
  const footerIdx = findFooterCrosslinks(body);

  let newBody;
  if (footerIdx >= 0) {
    // Find the insertion point: just before the footer line (and any preceding ---)
    let insertIdx = footerIdx;
    // Check if line before footer is --- (horizontal rule)
    if (insertIdx > 0 && lines[insertIdx - 1].trim() === '---') {
      // keep the --- before footer; insert before ---
      // Actually let's insert between --- and footer, or before ---
      // Let's insert a new section before the --- that precedes the footer
      insertIdx = insertIdx - 1;
    }
    const before = lines.slice(0, insertIdx);
    const after = lines.slice(insertIdx);
    newBody = before.join('\n') + additionBlock + '\n' + after.join('\n');
  } else {
    // No footer found, just append
    newBody = body + additionBlock;
  }

  const newContent = frontmatter + newBody;
  const newWordCount = countWords(newBody);

  fs.writeFileSync(filePath, newContent, 'utf-8');
  modifiedCount++;
  results.push({ slug, before: wordCount, after: newWordCount, status: 'MODIFIED' });
}

