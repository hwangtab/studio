# 티어 A + 티어 B 합산
ALL_CONTENT = {**TIER_A_CONTENT, **TIER_B_CONTENT}


def add_section(filepath, fname):
    """파일에 고유 콘텐츠 섹션 추가 (## 마치며 직전에 삽입)."""
    content_block = ALL_CONTENT.get(fname)
    if not content_block:
        return None

    with open(filepath, 'r', encoding='utf-8') as f:
        raw = f.read()

    # 이미 추가된 파일 스킵 (섹션 헤더로 확인)
    section_header = content_block.split('\n\n')[0].strip()
    if section_header in raw:
        return None

    # ## 마치며 앞에 삽입
    insertion = f'\n---\n\n{content_block}\n'

    # ## 마치며 바로 앞에 삽입
    new_raw = re.sub(
        r'\n## 마치며\n',
        insertion + '\n## 마치며\n',
        raw,
        count=1
    )

    if new_raw == raw:
        # 마치며 섹션이 없는 경우 — 푸터 링크 앞에 삽입
        new_raw = re.sub(
            r'\n\[([^\]]+)\]\(/[^)]+\)',
            insertion + '\n[\\1](/)',
            raw,
            count=1
        )
        # 위도 실패하면 파일 끝에 추가
        if new_raw == raw:
            new_raw = raw.rstrip() + '\n' + insertion

    if new_raw == raw:
        return None
    return new_raw


def main():
    modified = 0
    skipped = 0
    for fname in sorted(ALL_CONTENT.keys()):
        filepath = os.path.join(STORIES_DIR, fname)
        if not os.path.exists(filepath):
            print(f"  파일 없음: {fname}")
            skipped += 1
            continue
        result = add_section(filepath, fname)
        if result is not None:
            with open(filepath, 'w', encoding='utf-8') as f:
                f.write(result)
            modified += 1
        else:
            skipped += 1

    print(f"완료: {modified}개 추가, {skipped}개 스킵")


if __name__ == '__main__':
    main()
