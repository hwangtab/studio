function stripMarkdownSyntax(text) {
  return text
    .replace(/%%[\w-]+%%/g, '')
    .replace(/!\[.*?\]\(.*?\)/g, '')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/^#{1,6}\s+/gm, '')
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/\*(.+?)\*/g, '$1')
    .replace(/^[-*]\s+/gm, '')
    .replace(/^---+$/gm, '')
    .replace(/`[^`]+`/g, '')
    .replace(/\|[^|\n]*\|/g, '')
    .replace(/\n+/g, ' ')
    .trim();
}

function countWords(text) {
  return text.split(/\s+/).filter(Boolean).length;
}

function getBodyContent(content) {
  return content.replace(/^---\n[\s\S]*?\n---\n/, '');
}

function getEffectiveWordCount(body) {
  const stripped = stripMarkdownSyntax(body);
  const words = countWords(stripped);
  const SHORTCODE_WORD_ESTIMATES = { 'online-fallback': 25, 'session-checklist': 60 };
  const bonus = [...body.matchAll(/%%([a-z-]+)%%/g)]
    .reduce((sum, m) => sum + (SHORTCODE_WORD_ESTIMATES[m[1]] ?? 15), 0);
  return words + bonus;
}

// ─────────────────────────────────────────────────────────
// Frontmatter 파서
// ─────────────────────────────────────────────────────────
function parseFrontmatter(content) {
  const match = content.match(/^---\n([\s\S]*?)\n---\n/);
  if (!match) return {};
  const yaml = match[1];
  const result = {};

  const titleMatch = yaml.match(/^title:\s*(.+)$/m);
  if (titleMatch) result.title = titleMatch[1].trim().replace(/^['"]|['"]$/g, '');

  const tagsBlockMatch = yaml.match(/^tags:\n((?:  - [^\n]+\n?)+)/m);
  if (tagsBlockMatch) {
    result.tags = tagsBlockMatch[1].match(/^  - (.+)$/gm)
      ?.map(l => l.replace(/^  - /, '').trim()) || [];
  } else {
    const tagsInlineMatch = yaml.match(/^tags:\s*\[([^\]]*)\]/m);
    if (tagsInlineMatch) {
      result.tags = tagsInlineMatch[1].split(',').map(t => t.trim().replace(/^['"]|['"]$/g, ''));
    } else {
      result.tags = [];
    }
  }

  return result;
}

