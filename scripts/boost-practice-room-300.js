// 슬러그에서 악기 종류 파악
function getInstrumentCategory(slug) {
  if (slug.includes('bass')) return 'bass';
  if (slug.includes('drum')) return 'drum';
  if (slug.includes('guitar') || slug.includes('acoustic')) return 'guitar';
  if (slug.includes('piano') || slug.includes('keyboard')) return 'piano';
  if (slug.includes('vocal') || slug.includes('voice') || slug.includes('band-vocal')) return 'vocal';
  if (slug.includes('audition')) return 'audition';
  if (slug.includes('anxiety')) return 'anxiety';
  if (slug.includes('accompanist')) return 'accompanist';
  return 'general';
}

// 파일별 고유 산문 생성 (파일 인덱스 기반으로 다른 내용 선택)
const usedProseIndices = {};

function generateProse(slug, fm, neededWords, fileIndex) {
  const category = getInstrumentCategory(slug);
  const pool = proseLibrary[category] || proseLibrary.general;

  // 파일마다 다른 산문 선택
  if (!usedProseIndices[category]) usedProseIndices[category] = 0;
  const idx = fileIndex % pool.length;
  let prose = pool[idx];

  // 단어 수 확인 후 필요하면 보충
  const proseWords = countWords(prose);

  if (proseWords < neededWords) {
    // 다른 proseSentences에서 추가
    const generalPool = proseLibrary.general;
    const extraIdx = (idx + 1) % generalPool.length;
    prose = prose + ' ' + generalPool[extraIdx];
  }

  return prose.trim();
}

