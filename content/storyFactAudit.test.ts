/** @jest-environment node */
import fs from 'node:fs';
import path from 'node:path';

/**
 * 2026-09-28 스토리 전수 사실 점검(4,074줄 대조, 약 100편 정정)에서 반복해 나온 틀린 자기 서술.
 * 같은 문구가 템플릿처럼 수십 편에 퍼져 있었고, 새 글이 옛 글을 본떠 쓰면 그대로 되살아난다.
 * 정본: 연습실 시간제 1시간 6,600원(부가세 포함, R02 1실, 사이트 온라인 예약), 합주실·드럼 풀세트 없음,
 * 녹음 1프로 25만원은 튠·믹싱 별도, 엔지니어 없는 셀프 대여만 없음(시간당 녹음은 있음).
 * 시장 시세(다른 연습실의 8,000~25,000원 등)를 말하는 줄은 대상이 아니다 — 자기 서술만 본다.
 */
const RULES: Array<[string, RegExp]> = [
  ['연습실 시간제 가격을 시장 범위로 적음', /(스튜디오 놀|저희|연신내[^.\n|]{0,8}놀)[^.\n|]{0,30}8,000~25,000|시간제 ?\(?8,000~25,000/],
  ['시간제가 없는 것처럼 읽히는 합주실 템플릿', /시간제 합주실이 아니라|시간 빌려 쓰는 합주실이 아니라/],
  ['시간제를 부정하는 입주형 설명', /시간(당|제로| 단위로) ?빌(리는|려주는)[^.\n]{0,15}(곳|데|게|연습실|합주실|방식)이 아니라/],
  ['시간제 대여를 안 한다고 말함', /시간제 대여는 아예|시간제 대신 월세 입주[^.\n]{0,20}로만/],
  ['엔지니어 동반 시간당 녹음까지 부정', /셀프 녹음·시간 대여/],
  ['없는 드럼 설비', /(드럼 풀 ?세트|드럼 키트|어쿠스틱 드럼)[^.\n]{0,4}완비|드럼 전용 방도 운영/],
  ['없는 합주실 운영', /(스튜디오 놀|저희)[^.\n]{0,20}모든 합주실|합주실\(음악연습실\)|24시간 합주실 (서비스|등을 제공)/],
  ['1프로 25만원에 튠·믹싱 포함 오기', /250,000원\*{0,2} \| 녹음 2시간 \+ 정밀 보컬 튠/],
  // 녹음 세션은 카카오톡 예약이 맞다(gangbuk1 표 등) — 연습실 줄만 본다.
  ['시간제 연습실을 카카오톡으로 예약', /(연습실|시간제)[^\n]{0,80}(카카오톡 (오픈채팅으로 )?(당일 )?예약[^.\n]{0,20}(가능|이용)|카카오톡 예약 후 즉시)/],
  // 2026-09-27~28 AI 인용 스토리 감사에서 드러난 대량 환각 셋. 전부 템플릿처럼 수십 편에 퍼져 있었다.
  // 정본: 건물 주차 불가(같은 길 KT은평지사 주차장 유료, 연신중학교 지하 공영주차장 약 1km),
  // 연습실 방은 장비 없는 방음방(월세 입주자 버스킹 장비 무료 대여는 별개), 상담은 무료(유료 컨설팅 없음).
  ['없는 대조동 공영주차장', /대조동 공영주차장|도보 1~2분[^.\n]{0,12}공영주차장/],
  ['연습실 방에 없는 장비 비치', /(스튜디오 놀|저희)[^.\n]{0,40}(PA 스피커|마이크 스탠드|업라이트 피아노|디지털 건반|피아노·건반|앰프)[^.\n]{0,20}(기본 구비|구비되어|갖춰져|갖추고 있|완비|준비되어 있)|개인실에서 PA 스피커로|PA 스피커에 연결해|장비\*\*: 업라이트 피아노 또는 디지털 건반/],
  ['없는 유료 컨설팅', /컨설팅\(시간당|컨설팅[^.\n]{0,10}시간당 ?₩?5(0,000|만)/],
];

describe('스토리 자기 서술 사실 가드 (2026-09-28 전수 점검)', () => {
  it.each(RULES)('%s', (_label, re) => {
    const dir = path.join(process.cwd(), 'content/stories');
    const hits: string[] = [];
    for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.md'))) {
      fs.readFileSync(path.join(dir, file), 'utf-8').split('\n').forEach((line, i) => {
        if (re.test(line)) hits.push(`${file}:${i + 1}: ${line.slice(0, 90)}`);
      });
    }
    expect(hits).toEqual([]);
  });
});
